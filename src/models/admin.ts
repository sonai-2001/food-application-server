import mongoose from "mongoose";

//* Creating a userSchema ~

const adminSchema = new mongoose.Schema({
  userName: {
    type: String,
    required: true,
    unique: true,
  },
  email: {
    type: String,
    required: true,
    match: [/\S+@\S+\.\S+/, "Please enter a valid email address"],
  },
  password: {
    type: String,
    required: true,
  },
  isVerified: {
    type: Boolean,
    default: false,
  },
  role: {
    type: String,
    default: "Admin",
  },
});

//* saving the schema ~
const Admin = mongoose.model("Admin", adminSchema);
export default Admin;
